import { buenosAiresDate, fromScaled, toScaled } from "@plant/shared";
import { z } from "zod";

import type { DraftRow } from "../file-upload/draft";
import {
  call,
  decimalOf,
  defaultSleep,
  holdingsReading,
  jsonOf,
  positive,
  rejected,
  unavailable,
} from "./http";
import { type ConnectionDeps, defineConnection } from "./port";

export const MERCADO_PAGO_BASE_URL = "https://api.mercadopago.com";

const REPORT = "/v1/account/release_report";

export const mercadoPagoCredentialsSchema = z.object({
  accessToken: z.string().regex(/^APP_USR-[A-Za-z0-9-]{20,200}$/),
});
type MercadoPagoCredentials = z.infer<typeof mercadoPagoCredentialsSchema>;

// The days a report covers, ending at the hour the read starts: enough for
// its first line to carry the balance the period opened with.
const REPORT_DAYS = 7;

// How long a report may take to be generated: Plant asks again after a
// wait that grows, within the read's budget.
const REPORT_WAITS_MS = [2000, 3000, 5000, 5000, 10000];

// The most wall time one read takes, requests and waits included; past it
// the read fails for the job's retry, which finds the report generated by
// then, as its period is the same within the hour.
export const MERCADO_PAGO_READ_BUDGET_MS = 30_000;

// The largest report Plant downloads: a week of releases is far smaller.
const REPORT_MAX_CHARS = 5_000_000;

const listSchema = z.array(
  z.object({
    begin_date: z.string(),
    end_date: z.string(),
    file_name: z.string().nullish(),
    status: z.string().nullish(),
  }),
);

const FILE_NAME = /^[A-Za-z0-9._-]{1,200}$/;

// One line of a CSV report, split by its separator; a field in double quotes
// may hold the separator, and two double quotes in it are one.
function fieldsOf(line: string, separator: string): string[] {
  const fields: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const char = line[i]!;
    if (quoted) {
      if (char === '"' && line[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === separator) {
      fields.push(field.trim());
      field = "";
    } else field += char;
  }
  fields.push(field.trim());
  return fields;
}

// An amount as the report prints it: a decimal point, or a decimal comma
// where the separator is a semicolon.
function amountOf(text: string | undefined): string | null {
  const decimal = decimalOf(
    /^-?\d+,\d+$/.test(text ?? "") ? text!.replace(",", ".") : text,
  );
  if (decimal === null) return null;
  try {
    return fromScaled(toScaled(decimal));
  } catch {
    return null;
  }
}

// The account's available balance in pesos at the report's end: the
// balance on its last line that prints one. null when no line does.
export function balanceOf(csv: string): string | null {
  const lines = csv.replace(/^﻿/, "").split(/\r?\n/).filter(Boolean);
  const header = lines[0] ?? "";
  const separator =
    header.split(";").length > header.split(",").length ? ";" : ",";
  const columns = fieldsOf(header, separator).map((each) => each.toUpperCase());
  const balanceAt = columns.indexOf("BALANCE_AMOUNT");
  const currencyAt = columns.indexOf("CURRENCY");
  if (balanceAt < 0) return null;
  let balance: string | null = null;
  for (const line of lines.slice(1)) {
    const fields = fieldsOf(line, separator);
    const currency = currencyAt < 0 ? "ARS" : fields[currencyAt];
    const amount = amountOf(fields[balanceAt]);
    if (amount !== null && (currency === "ARS" || currency === "")) {
      balance = amount;
    }
  }
  return balance;
}

// Mercado Pago by the user's own production access token, which Mercado Pago
// grants every permission, so the user confirms they understand Plant only
// reads. Its API has no balance, so Plant asks for the report of released
// money (the one POST), waits while Mercado Pago generates it, and reads the
// available balance it closes with as cash in pesos.
export function mercadoPagoConnection({
  baseUrl = MERCADO_PAGO_BASE_URL,
  fetch: get = fetch,
  now = () => new Date(),
  sleep = defaultSleep,
  timeoutMs = 10_000,
  budgetMs = MERCADO_PAGO_READ_BUDGET_MS,
  clock = () => performance.now(),
}: ConnectionDeps = {}) {
  let deadline = Number.POSITIVE_INFINITY;
  const left = () => deadline - clock();

  const request = async (
    path: string,
    { accessToken }: MercadoPagoCredentials,
    init: RequestInit = {},
  ): Promise<Response> => {
    const budget = Math.min(timeoutMs, left());
    if (budget <= 0) throw unavailable();
    const response = await call(
      get,
      `${baseUrl}${path}`,
      {
        ...init,
        headers: {
          ...init.headers,
          Authorization: `Bearer ${accessToken}`,
          Accept: "application/json",
        },
      },
      budget,
    );
    if (response.status === 401 || response.status === 403) throw rejected();
    return response;
  };

  // The report of the period, once Mercado Pago lists it as generated.
  const listed = async (
    credentials: MercadoPagoCredentials,
    begin: Date,
    end: Date,
  ): Promise<string | null> => {
    const response = await request(`${REPORT}/list`, credentials);
    const parsed = listSchema.safeParse(await jsonOf(response));
    if (!response.ok || !parsed.success) throw unavailable();
    const found = parsed.data.find(
      (each) =>
        Date.parse(each.begin_date) === begin.getTime() &&
        Date.parse(each.end_date) === end.getTime(),
    );
    if (!found?.file_name || !FILE_NAME.test(found.file_name)) return null;
    if (found.status && /^(pending|processing|enqueued)$/i.test(found.status)) {
      return null;
    }
    return found.file_name;
  };

  const report = async (credentials: MercadoPagoCredentials) => {
    deadline = clock() + budgetMs;
    const end = new Date(now());
    end.setUTCMinutes(0, 0, 0);
    const begin = new Date(end.getTime() - REPORT_DAYS * 86_400_000);
    let file = await listed(credentials, begin, end);
    if (file === null) {
      const created = await request(REPORT, credentials, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          begin_date: begin.toISOString().replace(/\.\d{3}Z$/, "Z"),
          end_date: end.toISOString().replace(/\.\d{3}Z$/, "Z"),
        }),
      });
      // 202: generating. Anything else, a 203 included (dates it does not
      // take), is for a later attempt.
      if (created.status !== 202 && created.status !== 200) {
        throw unavailable();
      }
      for (const wait of REPORT_WAITS_MS) {
        if (wait >= left()) break;
        await sleep(wait);
        file = await listed(credentials, begin, end);
        if (file !== null) break;
      }
    }
    if (file === null) throw unavailable();
    const response = await request(`${REPORT}/${file}`, credentials);
    if (!response.ok) throw unavailable();
    const csv = await response.text().catch((cause: unknown) => {
      throw unavailable(cause);
    });
    if (csv.length > REPORT_MAX_CHARS) throw unavailable();
    return { csv, end };
  };

  return defineConnection({
    provider: "mercadopago",
    credentials: mercadoPagoCredentialsSchema,
    secrets: ["accessToken"],
    hintField: "accessToken",
    readOnly: "none",
    drafts: ["holdings"],
    // The token's own user proves it works.
    check: async (credentials) => {
      deadline = clock() + budgetMs;
      const response = await request("/users/me", credentials);
      if (!response.ok) throw unavailable();
    },
    async read(credentials) {
      const { csv, end } = await report(credentials);
      const balance = balanceOf(csv);
      const rows: DraftRow[] = positive(balance)
        ? [
            {
              symbol: "ARS",
              quantity: balance,
              price: null,
              value: null,
              currency: "ARS",
              // Which line closes the report is read from its documentation,
              // so the review asks the user to look.
              confidence: "medium",
              page: null,
            },
          ]
        : [];
      const reading = holdingsReading(rows, balance === null ? 1 : 0, now());
      reading.draft.documentDate = buenosAiresDate(end);
      return reading;
    },
  });
}
